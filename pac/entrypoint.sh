#!/bin/sh
# Render a proxy auto-config (PAC) file from environment variables into a tmpfs
# and serve it read-only over HTTP with busybox httpd. Fails closed on invalid
# input. The PAC hands out the proxy ONLY for PAC_HOSTS (label-boundary suffix
# match, same rule as ByeDPI's SPLIT_HOSTS); every other host stays DIRECT, so a
# device set to "automatic proxy configuration" uses the NAS line for everything
# except the blocked sites.
set -eu

WEB_DIR=/run/pac
PAC="$WEB_DIR/proxy.pac"
HTTPD_CONF="$WEB_DIR/httpd.conf"

: "${PAC_PROXY:?PAC_PROXY must be the HOST:PORT clients should use, e.g. 192.168.1.10:8888}"
: "${PAC_HOSTS:?PAC_HOSTS must list the hostnames to send through the proxy (space-separated)}"
PAC_PORT="${PAC_PORT:-8080}"

# PAC_PROXY is host:port with a literal IPv4/hostname and a numeric port.
case "$PAC_PROXY" in
  *[!A-Za-z0-9.:_-]*|'') echo "invalid PAC_PROXY: $PAC_PROXY" >&2; exit 64 ;;
esac
case "${PAC_PROXY##*:}" in ''|*[!0-9]*) echo "PAC_PROXY must end in :PORT" >&2; exit 64 ;; esac
case "$PAC_PORT" in ''|*[!0-9]*) echo "PAC_PORT must be an integer" >&2; exit 64 ;; esac

if [ ! -w "$WEB_DIR" ]; then
  echo "$WEB_DIR is not writable by uid $(id -u); mount it as tmpfs with uid/gid (see docker-compose.yml)" >&2
  exit 70
fi

# Build the JS host array, validating each entry as a DNS name.
hosts_js=""
for h in $PAC_HOSTS; do
  case "$h" in
    *[!A-Za-z0-9.-]*|''|.*|*.) echo "invalid PAC_HOSTS entry: $h" >&2; exit 64 ;;
  esac
  hosts_js="$hosts_js\"$(printf '%s' "$h" | tr 'A-Z' 'a-z')\","
done
hosts_js="${hosts_js%,}"

cat > "$PAC" <<EOF
// Generated by dsm-selective-dpi-proxy. Do not edit by hand; set PAC_HOSTS /
// PAC_PROXY in the stack variables and redeploy.
function FindProxyForHost(host, url) {
  host = host.toLowerCase();
  var proxy = "PROXY $PAC_PROXY";
  var hosts = [$hosts_js];
  for (var i = 0; i < hosts.length; i++) {
    var d = hosts[i];
    if (host === d || host.length > d.length &&
        host.substring(host.length - d.length - 1) === "." + d) {
      return proxy;
    }
  }
  return "DIRECT";
}
EOF
chmod 0444 "$PAC"

# busybox httpd serves .pac with the PAC MIME type browsers expect.
cat > "$HTTPD_CONF" <<'EOF'
.pac:application/x-ns-proxy-autoconfig
EOF

echo "pac: serving /proxy.pac on :$PAC_PORT -> PROXY $PAC_PROXY for [$PAC_HOSTS]"
exec httpd -f -v -p "0.0.0.0:$PAC_PORT" -h "$WEB_DIR" -c "$HTTPD_CONF"
